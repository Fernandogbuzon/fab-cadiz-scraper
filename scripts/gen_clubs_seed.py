"""
Generate the Central `clubs` + `club_team_aliases` seed from adesa80-web's logoMap.js.

Why: the web resolves team logos client-side via src/lib/logoMap.js (ordered
substring patterns -> /logos/<file>). We port that mapping into the Central DB
(reusing the existing clubs + club_team_aliases tables) so logos live in the DB
and can be linked to teams. `club_team_aliases.priority` reproduces logoMap's
order-sensitivity (earlier pattern = higher priority = wins on overlap).

Output: sql/004_seed_clubs_logos.sql  (idempotent; safe to re-run).
Run:    python scripts/gen_clubs_seed.py
Then apply the generated SQL on Central (fab-cadiz-central).
"""

